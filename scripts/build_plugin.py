#!/usr/bin/env python3
"""Build the all-in-one `caffeinity` plugin from its sources.

    python scripts/build_plugin.py --from-dir ~/clones     # skills from local clones
    python scripts/build_plugin.py                         # skills from GitHub (needs `gh auth`)
    python scripts/build_plugin.py --agents-only --check   # exit 1 if the agents are stale

Two generated parts, never edited by hand:

  plugins/caffeinity/agents/<name>.md   one Claude Code subagent per workflow, rendered from
                                         plugins/caffeinity/agents.json and the workflow's table in
                                         caffeinity-routing/references/workflows.md
  plugins/caffeinity/skills/<name>/     every published skill, copied from its repo at HEAD; the
                                         list is skills-site's site/skills.json (mods and legacy
                                         archives excluded), and SOURCES.md records each commit

The same folder is a Claude Code plugin (.claude-plugin/plugin.json) and a portable / Codex plugin
(plugin.json), so one copy serves both.
"""
import argparse
import io
import json
import re
import shutil
import subprocess
import sys
import tarfile
import urllib.request
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
PLUGIN = ROOT / "plugins" / "caffeinity"
ROUTING = ROOT / "plugins" / "caffeinity-routing" / "skills" / "caffeinity-routing"
WORKFLOWS = ROUTING / "references" / "workflows.md"
MANIFEST_URL = "https://raw.githubusercontent.com/arm-pz/skills-site/main/site/skills.json"
REPO_META = {"README.md", "LICENSE", "LICENSE.md", "CHANGELOG.md", "CONTRIBUTING.md"}
REPO_META_DIRS = {".claude-plugin", ".codex-plugin", ".github", ".git", "tests", "node_modules"}


def workflows():
    """{"W1": {"title", "steps": [cells...], "notes": [paragraph lines]}} from workflows.md."""
    flows, cur = {}, None
    for line in WORKFLOWS.read_text(encoding="utf-8").splitlines():
        m = re.match(r"^## (W\d+) (.+)$", line)
        if m:
            cur = flows.setdefault(m.group(1), {"title": m.group(2), "steps": [], "notes": []})
            continue
        if cur is None:
            continue
        cells = [c.strip() for c in line.strip().strip("|").split("|")]
        if line.startswith("|") and cells[0].isdigit():
            cur["steps"].append(cells)
        elif line.strip() and not line.startswith("|"):
            cur["notes"].append(line.strip())
    return flows


def skills_in(cells):
    return re.findall(r"`([a-z0-9-]+)`", cells[1])


def render_agent(spec, flow):
    names = []
    for step in flow["steps"]:
        names += [n for n in skills_in(step) if n not in names]
    rows = "\n".join(f"| {' | '.join(step)} |" for step in flow["steps"])
    notes = " ".join(flow["notes"])
    return f"""---
name: {spec['name']}
description: {json.dumps(spec['description'], ensure_ascii=False)}
skills: [{', '.join(names)}]
model: inherit
color: {spec['color']}
---

<!-- Generated by scripts/build_plugin.py from agents.json and caffeinity-routing's workflows.md ({spec['workflow']}). Edit those, then rebuild. -->

# {spec['name']}

{spec['role']} You run workflow {spec['workflow']} of the caffeinity skills, "{flow['title']}", by handing each step to the skill that owns it.

## Route

| Step | Skill | Receives | Hands on | Stops when |
| --- | --- | --- | --- | --- |
{rows}

{notes}

## Rules

- **Each step belongs to its skill.** Follow that skill's SKILL.md and references; do not redo its work from memory. If a step's skill is not available, say which one is missing and how to install it (`npx skills add arm-pz/<skill>`), mark the step skipped, and never improvise it.
- **Carry outputs forward verbatim.** What a step hands on is the next step's input. Summarising between steps loses the evidence the next skill checks.
- **Stop at gates.** When a step's "Stops when" condition holds, stop there, say so, and ask the user. A gate is never routed around.
- **Confirm before anything public or irreversible:** a push, a deploy, a published listing, a sent message.
- **Optional steps run only when they apply.** Say why you ran or skipped one.

## Report

Lead with one line per step: skill, status (done, skipped and why, or stopped at its gate), and where its output is. Then the one next action. Say which steps actually ran and which were only planned.
"""


def build_agents(check=False):
    spec = json.loads((PLUGIN / "agents.json").read_text(encoding="utf-8"))
    flows = workflows()
    out_dir = PLUGIN / "agents"
    wanted = {f"{a['name']}.md": render_agent(a, flows[a["workflow"]]) for a in spec["agents"]}
    stale = [n for n, text in wanted.items()
             if not (out_dir / n).is_file() or (out_dir / n).read_text(encoding="utf-8") != text]
    extra = [p.name for p in out_dir.glob("*.md") if p.name not in wanted] if out_dir.is_dir() else []
    if check:
        for n in stale + extra:
            print(f"stale: agents/{n}")
        return 1 if stale or extra else 0
    out_dir.mkdir(parents=True, exist_ok=True)
    for n in extra:
        (out_dir / n).unlink()
    for n, text in wanted.items():
        (out_dir / n).write_text(text, encoding="utf-8")
    print(f"agents: {len(wanted)} written")
    return 0


def select(files, path):
    if path == ".":
        return {k: v for k, v in files.items()
                if k.split("/")[0] not in REPO_META | REPO_META_DIRS}
    prefix = path.rstrip("/") + "/"
    return {k[len(prefix):]: v for k, v in files.items() if k.startswith(prefix)}


def from_tarball(blob):
    files = {}
    with tarfile.open(fileobj=io.BytesIO(blob), mode="r:gz") as tar:
        for m in tar.getmembers():
            if m.isfile():
                files[m.name.split("/", 1)[1]] = tar.extractfile(m).read()
    return files


def fetch_github(repo):
    blob = subprocess.run(["gh", "api", f"repos/{repo}/tarball"], capture_output=True, check=True).stdout
    sha = subprocess.run(["gh", "api", f"repos/{repo}/commits/HEAD", "--jq", ".sha"],
                         capture_output=True, text=True, check=True).stdout.strip()
    return from_tarball(blob), sha


def fetch_local(base):
    def fetch(repo):
        d = Path(base) / repo.split("/", 1)[1]
        names = subprocess.run(["git", "-C", str(d), "ls-files", "-z"], capture_output=True,
                               text=True, check=True).stdout.split("\0")
        sha = subprocess.run(["git", "-C", str(d), "rev-parse", "HEAD"], capture_output=True,
                             text=True, check=True).stdout.strip()
        return {n: (d / n).read_bytes() for n in names if n}, sha
    return fetch


def build_skills(manifest, fetch):
    dest = PLUGIN / "skills"
    if dest.exists():
        shutil.rmtree(dest)
    rows, cache = [], {}
    for s in sorted(manifest["skills"], key=lambda s: s["name"]):
        if s.get("repo") is None or s.get("kind") == "mod":
            continue
        if s["repo"] == "arm-pz/caffeinity-skills":   # lives in this repo
            files = {str(p.relative_to(ROUTING)): p.read_bytes() for p in ROUTING.rglob("*")
                     if p.is_file() and "__pycache__" not in p.parts}
            sha = "this repo"
        else:
            if s["repo"] not in cache:
                cache[s["repo"]] = fetch(s["repo"])
            full, sha = cache[s["repo"]]
            files = select(full, s["path"])
        if "SKILL.md" not in files:
            raise SystemExit(f"{s['name']}: no SKILL.md under {s['repo']}:{s['path']}")
        for rel, data in files.items():
            p = dest / s["name"] / rel
            p.parent.mkdir(parents=True, exist_ok=True)
            p.write_bytes(data)
        rows.append(f"| {s['name']} | [{s['repo']}](https://github.com/{s['repo']}) | `{sha[:7]}` |")
    (PLUGIN / "SOURCES.md").write_text(
        "# Bundled skills\n\nGenerated by `scripts/build_plugin.py`; each folder under `skills/` is "
        "a copy of the skill at the commit below. Change the source repo, not this copy.\n\n"
        "| Skill | Source | Commit |\n| --- | --- | --- |\n" + "\n".join(rows) + "\n", encoding="utf-8")
    print(f"skills: {len(rows)} bundled")
    return len(rows)


def stamp_version():
    """Bump both manifests' version when the bundled content changes, so installs update.

    Claude Code keeps users on a plugin.json version until it changes; an unchanged rebuild keeps
    the same version, so a scheduled run that finds nothing new does not churn it.
    """
    import datetime as dt
    import hashlib
    digest = hashlib.sha256()
    for p in sorted(list((PLUGIN / "agents").rglob("*")) + list((PLUGIN / "skills").rglob("*"))):
        if p.is_file():
            digest.update(p.relative_to(PLUGIN).as_posix().encode() + b"\0" + p.read_bytes() + b"\0")
    digest = digest.hexdigest()[:16]
    paths = [PLUGIN / ".claude-plugin" / "plugin.json", PLUGIN / "plugin.json"]
    docs = [json.loads(p.read_text(encoding="utf-8")) for p in paths]
    if all(d.get("metadata", {}).get("bundleDigest") == digest for d in docs):
        print(f"version: {docs[0]['version']} (content unchanged)")
        return
    version = "1." + dt.datetime.now(dt.timezone.utc).strftime("%Y%m%d.%H%M")
    for p, d in zip(paths, docs):
        d["version"] = version
        d.setdefault("metadata", {})["bundleDigest"] = digest
        p.write_text(json.dumps(d, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")
    print(f"version: {version}")


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--from-dir", help="read skill repos from local clones in this folder")
    ap.add_argument("--manifest", help="local site/skills.json instead of the published one")
    ap.add_argument("--agents-only", action="store_true")
    ap.add_argument("--check", action="store_true", help="with --agents-only: exit 1 if stale")
    a = ap.parse_args(argv)
    code = build_agents(check=a.check)
    if a.agents_only or code:
        return code
    if a.manifest:
        manifest = json.loads(Path(a.manifest).read_text(encoding="utf-8"))
    else:
        with urllib.request.urlopen(MANIFEST_URL, timeout=30) as r:
            manifest = json.load(r)
    build_skills(manifest, fetch_local(a.from_dir) if a.from_dir else fetch_github)
    stamp_version()
    return 0


if __name__ == "__main__":
    sys.exit(main())
